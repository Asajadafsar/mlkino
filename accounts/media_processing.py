"""Bounded raster decoding and privacy-preserving responsive image derivatives.

Storage names are generated by the server. Existing URLs are never overwritten
or deleted by this module; gradual conversion can therefore preserve old links.
SVG and other active/vector documents do not enter the raster decoder.
"""
from dataclasses import dataclass
from io import BytesIO
from pathlib import PurePosixPath
import uuid
import warnings

from django.conf import settings
from django.core.files.base import ContentFile
from django.core.files.uploadedfile import SimpleUploadedFile
from django.core.files.storage import default_storage
from PIL import Image, ImageOps, UnidentifiedImageError
from rest_framework.exceptions import ValidationError

MAX_BYTES = 5 * 1024 * 1024
MAX_PIXELS = 24_000_000
MAX_EDGE = 12_000
MIMES = {'JPEG': {'image/jpeg', 'image/jpg'}, 'PNG': {'image/png'},
         'WEBP': {'image/webp'}, 'AVIF': {'image/avif'}, 'GIF': {'image/gif'}}

@dataclass(frozen=True)
class EncodedImage:
    content: bytes
    width: int
    height: int
    mime: str = 'image/webp'
    extension: str = 'webp'


def decode_raster(upload, max_bytes=MAX_BYTES):
    """Verify signature, declared MIME, dimensions and full image integrity."""
    size = getattr(upload, 'size', None)
    if size is not None and size > max_bytes:
        raise ValidationError('حجم تصویر باید حداکثر ۵ مگابایت باشد.')
    try:
        upload.seek(0)
        raw = upload.read(max_bytes + 1)
        upload.seek(0)
    except (AttributeError, OSError, ValueError) as exc:
        raise ValidationError('فایل تصویر قابل خواندن نیست.') from exc
    if not raw or len(raw) > max_bytes:
        raise ValidationError('حجم تصویر باید بین یک بایت و ۵ مگابایت باشد.')
    try:
        with warnings.catch_warnings():
            warnings.simplefilter('error', Image.DecompressionBombWarning)
            with Image.open(BytesIO(raw)) as candidate:
                image_format = candidate.format
                if image_format not in MIMES:
                    raise ValidationError('فقط تصاویر JPEG، PNG، WebP، AVIF یا GIF ثابت مجاز هستند.')
                declared = (getattr(upload, 'content_type', '') or '').split(';')[0].strip().lower()
                if declared and declared not in MIMES[image_format]:
                    raise ValidationError('نوع اعلام‌شده تصویر با محتوای واقعی فایل مطابقت ندارد.')
                width, height = candidate.size
                if width < 1 or height < 1 or width * height > MAX_PIXELS or max(width, height) > MAX_EDGE:
                    raise ValidationError('ابعاد تصویر بیش از حد مجاز است؛ تصویر کوچک‌تری انتخاب کنید.')
                if getattr(candidate, 'n_frames', 1) > 1:
                    raise ValidationError('برای این بخش تصویر ثابت بارگذاری کنید؛ تصویر متحرک مجاز نیست.')
                candidate.verify()
            with Image.open(BytesIO(raw)) as source:
                source.load()
                corrected = ImageOps.exif_transpose(source)
                # A fresh pixel-only image drops GPS, EXIF, comments, ICC and
                # original encoding chunks without losing alpha transparency.
                mode = 'RGBA' if 'A' in corrected.getbands() or 'transparency' in corrected.info else 'RGB'
                converted = corrected.convert(mode)
                clean = Image.new(mode, converted.size)
                clean.paste(converted)
                return clean
    except ValidationError:
        raise
    except (UnidentifiedImageError, OSError, SyntaxError, ValueError,
            Image.DecompressionBombError, Image.DecompressionBombWarning) as exc:
        raise ValidationError('محتوای تصویر معتبر نیست یا فایل آسیب دیده است.') from exc


def encode_image(image, max_width=1600, quality=82, output='WEBP'):
    thumbnail = image.copy()
    thumbnail.thumbnail((max_width, max_width), Image.Resampling.LANCZOS)
    buffer = BytesIO()
    image_format = output.upper()
    if image_format not in ('WEBP', 'AVIF') or image_format not in Image.SAVE:
        image_format = 'WEBP'
    options = {'quality': quality}
    if image_format == 'WEBP':
        options['method'] = 4
    thumbnail.save(buffer, image_format, **options)
    return EncodedImage(buffer.getvalue(), thumbnail.width, thumbnail.height,
                        'image/avif' if image_format == 'AVIF' else 'image/webp',
                        'avif' if image_format == 'AVIF' else 'webp')


def optimized_avatar(upload):
    if upload is None:
        return None
    image = decode_raster(upload)
    encoded = encode_image(image, max_width=512, quality=82)
    return SimpleUploadedFile(uuid.uuid4().hex + '.webp', encoded.content, content_type=encoded.mime)


def image_derivatives(upload, sizes=(320, 768, 1600), include_avif=False):
    image = decode_raster(upload)
    image.load()
    results = []
    seen = set()
    for size in sizes:
        bounded = min(size, max(image.size))
        if bounded in seen:
            continue
        seen.add(bounded)
        results.append(encode_image(image, max_width=bounded))
        if include_avif and 'AVIF' in Image.SAVE:
            results.append(encode_image(image, max_width=bounded, output='AVIF'))
    return results


def store_property_image(upload, request=None, *, storage=None, include_avif=False):
    """Return a canonical URL and sizes, rolling back files on storage failure."""
    storage = storage or default_storage
    encoded = image_derivatives(upload, include_avif=include_avif)
    prefix = 'properties/' + uuid.uuid4().hex
    saved = []
    variants = []
    try:
        for image in encoded:
            path = storage.save(f'{prefix}/{image.width}x{image.height}.{image.extension}', ContentFile(image.content))
            saved.append(path)
            url = storage.url(path)
            if request is not None:
                url = request.build_absolute_uri(url)
            elif url.startswith('/'):
                base = getattr(settings, 'PANEL_SETTINGS_PUBLIC_BASE_URL', '')
                if base:
                    url = base.rstrip('/') + url
            variants.append({'url': url, 'width': image.width, 'height': image.height,
                             'mime': image.mime, 'bytes': len(image.content)})
        webp = [v for v in variants if v['mime'] == 'image/webp']
        return {'url': webp[-1]['url'], 'variants': variants, 'stored_paths': saved}
    except Exception:
        for path in saved:
            storage.delete(path)
        raise


def local_media_path(url):
    """Recognize only known storage URLs; never fetch an arbitrary remote URL."""
    from urllib.parse import urlsplit, unquote
    parsed = urlsplit(url)
    media = urlsplit(getattr(settings, 'MEDIA_URL', '/media/'))
    base = urlsplit(getattr(settings, 'PANEL_SETTINGS_PUBLIC_BASE_URL', ''))
    if parsed.query or parsed.fragment:
        return None
    if parsed.netloc and parsed.netloc not in {media.netloc, base.netloc}:
        return None
    prefix = media.path
    if not prefix or not parsed.path.startswith(prefix):
        return None
    relative = unquote(parsed.path[len(prefix):])
    path = PurePosixPath(relative)
    if not relative or path.is_absolute() or '..' in path.parts or '\\' in relative:
        return None
    return str(path)


def sanitized_document(upload, images_only=False):
    """Images are pixel-normalized; PDF stays opaque and is attachment-only."""
    if upload is None:
        return None
    upload.seek(0)
    prefix=upload.read(5);upload.seek(0)
    if prefix==b'%PDF-' and not images_only:
        if upload.size>10*1024*1024:
            raise ValidationError('حجم مدرک باید حداکثر ۱۰ مگابایت باشد.')
        mime=(getattr(upload,'content_type','') or '').split(';')[0].lower()
        if mime not in ('','application/pdf'):
            raise ValidationError('نوع اعلام‌شده مدرک با محتوای PDF مطابقت ندارد.')
        data=upload.read(10*1024*1024+1);upload.seek(0)
        if len(data)>10*1024*1024 or not data.rstrip().endswith(b'%%EOF'):
            raise ValidationError('فایل PDF معتبر و کامل نیست.')
        if any(marker in data for marker in (b'/JavaScript',b'/JS',b'/Launch',b'/EmbeddedFile',b'/RichMedia',b'/XFA',b'/Encrypt')):
            raise ValidationError('فایل PDF دارای محتوای فعال، پیوست یا رمزگذاری مجاز نیست؛ نسخه ساده مدرک را بارگذاری کنید.')
        return SimpleUploadedFile(uuid.uuid4().hex+'.pdf',data,content_type='application/pdf')
    image=decode_raster(upload)
    encoded=encode_image(image,max_width=2000,quality=88)
    return SimpleUploadedFile(uuid.uuid4().hex+'.webp',encoded.content,content_type='image/webp')
